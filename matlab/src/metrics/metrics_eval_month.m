function [Products, ACC] = metrics_eval_month(cfg, Products, ACC, t, Tk, refTag, lonVec, latVec, landMask)
%METRICS_EVAL_MONTH Evaluate all products in one month and update ACC.
%
% refTag: reference field name in Products, e.g., 'Mascon' or 'RAW' (if you treat RAW as reference).
%
% Products.(tag).metrics.global will be attached.

    %#ok<NASGU> cfg kept for interface compatibility
    ctx = struct( ...
        't', t, ...
        'Tk', Tk, ...
        'refTag', refTag, ...
        'lonVec', lonVec, ...
        'latVec', latVec, ...
        'landMask', landMask);
    [Products, ACC] = metrics_eval_month_ctx(Products, ACC, ctx);
end
